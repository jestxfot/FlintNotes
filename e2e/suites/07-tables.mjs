// Tables: Markdown tables edited as tables; ```table blocks with formulas, column types, merged cells.
export const viewport = { width: 1400, height: 1000 }
export const vault = {
  plugins: ['tables'],
  files: {
    'Plain.md': '# Plain\n\n| Name  | Qty |\n| ----- | --: |\n| Apple | 3   |\n| Pear  | 10  |\n\nafter\n',
    'Ext.md':
      '# Ext\n\n```table\n| Товар | Цена {number} | Кол-во {number} | Сумма {number} | Готово {checkbox} | Статус {select: новый, готово} | Срок {date} |\n| --- | --- | --- | --- | --- | --- | --- |\n| Клавиатура | 3500 | 2 | =B1*C1 | x | новый | 2026-10-12 |\n| Мышь | 1200 | 1 | =B2*C2 |  | готово |  |\n| Итого | < | < | =sum(D1:D2) | =count(Цена) | =D1/0 | =nope( |\n```\n\nafter\n',
    'Empty.md': 'start\n',
  },
}

export async function run(t) {
  const { page, ok, wait, read, leaf } = t
  const table = page.locator(`${leaf} .ft`)
  const cell = (r, c) => table.locator(`[data-r="${r}"][data-c="${c}"]`)
  const menu = (label) => page.locator('.ft-menu button', { hasText: label })
  const grid = () => table.locator('tbody tr').evaluateAll((rows) => rows.map((tr) => [...tr.querySelectorAll('td')].map((td) => td.innerText.trim())))
  const key = (name) => page.keyboard.press(name)

  await t.open('Plain')
  ok('a markdown table is drawn as a table', (await table.count()) === 1 && JSON.stringify(await grid()) === JSON.stringify([['Apple', '3'], ['Pear', '10']]) && !(await t.text()).includes('| ---'), JSON.stringify(await grid()))
  ok('column alignment kept', (await cell(0, 1).evaluate((td) => td.style.textAlign)) === 'right')

  await cell(0, 0).click()
  await page.keyboard.type(' Pie')
  await key('Enter')
  await wait(700)
  ok('a cell edit rewrites the table text, aligned', read('Plain.md').includes('| Name      | Qty |\n| --------- | --: |\n| Apple Pie | 3   |\n| Pear      | 10  |'), read('Plain.md'))
  ok('Enter moves to the cell below', (await cell(1, 0).locator('textarea').inputValue().catch(() => null)) === 'Pear')
  await key('Tab')
  await key('Tab')
  await wait(500)
  ok('Tab past the last cell adds a row', read('Plain.md').includes('| Pear      | 10  |\n|           |     |') && (await cell(2, 0).locator('textarea').count()) === 1, read('Plain.md'))
  await page.keyboard.type('Kiwi')
  await key('Tab')
  await page.keyboard.type('a')
  await key('Shift+Enter')
  await page.keyboard.type('b')
  await key('Enter')
  await wait(700)
  ok('Shift+Enter makes a line break in a cell', read('Plain.md').includes('| Kiwi      | a<br>b |'), read('Plain.md'))
  ok('the line break is drawn', (await cell(2, 1).locator('br').count()) === 1)

  await cell(-1, 1).click({ button: 'right' })
  await menu('Сортировать по убыванию').click()
  await wait(600)
  ok('sort by column', JSON.stringify((await grid()).map((row) => row[0])) === JSON.stringify(['Kiwi', 'Pear', 'Apple Pie']), JSON.stringify(await grid()))
  await cell(0, 1).click({ button: 'right' })
  await menu('Вставить столбец справа').click()
  await wait(400)
  await key('Control+a')
  await page.keyboard.type('Note')
  await key('Enter')
  await wait(600)
  ok('a column is inserted and named', read('Plain.md').includes('| Name      | Qty    | Note |'), read('Plain.md'))
  await cell(0, 0).click({ button: 'right' })
  await menu('Удалить строку').click()
  await wait(600)
  ok('a row is deleted', !read('Plain.md').includes('Kiwi') && (await grid()).length === 2)
  await table.hover()
  await table.locator('.ft-add-row').click()
  await wait(400)
  await page.keyboard.type('Plum')
  await key('Escape')
  await wait(400)
  ok('the add-row button adds a row; Escape cancels typing', (await grid()).length === 3 && !read('Plain.md').includes('Plum'), read('Plain.md'))
  await cell(-1, 0).click({ button: 'right' })
  await menu('По центру').click()
  await wait(600)
  ok('alignment is written to the delimiter row', /\| :-+: \| -+: \|/.test(read('Plain.md')), read('Plain.md'))
  ok('text around the table is untouched', read('Plain.md').startsWith('# Plain\n\n| Name') && read('Plain.md').endsWith('|\n\nafter\n'), JSON.stringify(read('Plain.md').slice(-30)))
  await table.hover()
  await page.locator(`${leaf} .lp-block-edit`).click()
  await wait(400)
  ok('the source is one click away', (await t.text()).includes('| Name') && (await table.count()) === 0)

  await t.open('Ext')
  let cellsNow = await grid()
  ok('formulas computed', cellsNow[0][3] === '7000' && cellsNow[1][3] === '1200' && cellsNow[2][1] === '8200', JSON.stringify(cellsNow))
  ok('merged cells', (await cell(2, 0).evaluate((td) => td.colSpan)) === 3 && cellsNow[2].length === 5, JSON.stringify(cellsNow[2]))
  ok('column by name, empty result, error', cellsNow[2][2] === '2' && cellsNow[2][3] === '' && cellsNow[2][4] === '#ОШИБКА', JSON.stringify(cellsNow[2]))
  ok('column letters and row numbers', /A\s*Товар\s*B\s*Цена\s*число/.test(await table.locator('thead').innerText()) && (await table.locator('tbody .ft-ref').allInnerTexts()).join('') === '123')
  ok('a number column is right-aligned', (await cell(0, 1).evaluate((td) => td.style.textAlign)) === 'right')

  await cell(1, 4).locator('input').click()
  await wait(600)
  ok('checkbox column', /\| Мышь\s+\| 1200\s+\| 1\s+\| =B2\*C2\s+\| x /.test(read('Ext.md')), read('Ext.md'))
  await cell(0, 5).click()
  await wait(200)
  ok('a select column offers its options', JSON.stringify(await cell(0, 5).locator('select option').allInnerTexts()) === JSON.stringify(['—', 'новый', 'готово']))
  await cell(0, 5).locator('select').selectOption('готово')
  await wait(600)
  ok('select writes the choice', /\| Клавиатура .*\| готово\s+\| 2026-10-12/.test(read('Ext.md')), read('Ext.md'))
  await cell(1, 6).click()
  await wait(200)
  await cell(1, 6).locator('input[type=date]').fill('2026-11-01')
  await key('Enter')
  await wait(600)
  ok('date column', /\| Мышь .*\| 2026-11-01\s+\|/.test(read('Ext.md')), read('Ext.md'))

  // Clicking from a cell being edited into another one used to lose the click and
  // send the typing into the note itself.
  await cell(0, 0).click()
  await wait(150)
  await cell(1, 1).click()
  await wait(300)
  ok('a click from an edited cell opens the clicked cell', (await cell(1, 1).locator('textarea').count()) === 1 && (await page.evaluate(() => document.activeElement?.className)) === 'ft-editor')
  await key('Control+a')
  await page.keyboard.type('2000')
  await key('Tab')
  await key('Escape')
  await wait(600)
  cellsNow = await grid()
  ok('changing a number recalculates formulas', cellsNow[1][3] === '2000' && cellsNow[2][1] === '9000', JSON.stringify(cellsNow))
  ok('typing in a cell never reaches the note', read('Ext.md').startsWith('# Ext\n\n```table\n') && read('Ext.md').endsWith('```\n\nafter\n'), read('Ext.md'))
  await cell(0, 3).click()
  await wait(200)
  ok('a formula cell edits its formula', (await cell(0, 3).locator('textarea').inputValue()) === '=B1*C1')
  await key('Escape')
  await wait(300)
  ok('headers keep their types in the text', read('Ext.md').includes('Цена {number}') && read('Ext.md').includes('Статус {select: новый, готово}'), read('Ext.md'))
  await cell(2, 0).click({ button: 'right' })
  await menu('Разъединить').click()
  await wait(600)
  ok('unmerge', (await grid())[2].length === 7 && (await cell(2, 0).evaluate((td) => td.colSpan)) === 1)
  await cell(2, 1).click({ button: 'right' })
  await menu('Объединить с ячейкой слева').click()
  await wait(600)
  ok('merge with the cell on the left', (await cell(2, 0).evaluate((td) => td.colSpan)) === 2 && /\| Итого\s+\| <\s+\|/.test(read('Ext.md')), read('Ext.md'))
  await cell(-1, 0).click({ button: 'right' })
  await menu('Тип: флажок').click()
  await wait(600)
  ok('column type set from the menu', read('Ext.md').includes('Товар {checkbox}'))

  await t.open('Empty')
  await key('Control+p')
  await page.keyboard.type('расширенную')
  await key('Enter')
  await wait(900)
  ok('the insert command adds a working extended table', read('Empty.md').startsWith('start\n\n```table\n| Товар') && (await grid())[2]?.includes('8200'), JSON.stringify(await grid().catch(() => 'none')))
}
